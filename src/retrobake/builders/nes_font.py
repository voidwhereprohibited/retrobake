TILE_BYTES = 16
CHR_BANK_BYTES = 8192


def _tile(glyph: str) -> bytes:
    rows = glyph.split()
    if len(rows) != 7 or any(len(r) != 5 or set(r) - {"#", "."} for r in rows):
        raise ValueError("glyphs are 7 rows of 5 pixels")
    plane0 = [sum(1 << (6 - i) for i, px in enumerate(r) if px == "#") for r in rows] + [0]
    return bytes(plane0) + bytes(8)  # colour 1 only: bit plane 1 is empty


def chr_bank() -> bytes:
    """8 KB CHR-ROM: font in pattern table 0, the rest blank."""
    tiles = b"".join(_tile(_GLYPHS[c]) for c in CHARSET)
    return tiles + bytes(CHR_BANK_BYTES - len(tiles))


def tiles_for(text: str) -> bytes:
    """Tile numbers for ``text``. Raises ValueError on characters the font lacks."""
    out = bytearray()
    for ch in text.upper():
        idx = CHARSET.find(ch)
        if idx < 0:
            raise ValueError(f"the NES font has no {ch!r}")
        out.append(idx)
    return bytes(out)
